export function geocodificar(municipio: string): [number, number] {
  const normalizar = (s: string) =>
    s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();

  const query = normalizar(municipio);

  for (const [key, coords] of Object.entries(COORDS)) {
    const normalKey = normalizar(key);
    if (query === normalKey || query.includes(normalKey) || normalKey.includes(query)) {
      return coords;
    }
  }

  // Centro de España como fallback
  return [40.4637, -3.7492];
}
